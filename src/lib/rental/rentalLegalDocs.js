export function legalDocById(docId) {
  return RENTAL_LEGAL_DOCS.find((d) => d.id === docId) || null;
}

export function bookingLegalSignatures(booking) {
  const raw = booking?.legal_doc_signatures;
  return raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : {};
}

/**
 * Resolve signature URL for a legal doc (from booking map or inspection).
 */
export function legalDocSignature(doc, booking, inspections) {
  if (!doc) return null;
  if (doc.source === 'inspection') {
    const list = (inspections || []).filter((i) => i.rental_booking_id === booking?.id);
    const hit =
      list.find((i) => i.inspection_type === doc.inspectionType && i.signature_url) || null;
    if (!hit?.signature_url) return null;
    return {
      signature_url: hit.signature_url,
      signed_at: hit.created_at || hit.updated_at || null,
      signer_name: hit.inspector_name || booking?.client_name || null,
      via: 'inspection',
    };
  }
  const entry = bookingLegalSignatures(booking)[doc.id];
  if (!entry?.signature_url) return null;
  return {
    signature_url: entry.signature_url,
    signed_at: entry.signed_at || null,
    signer_name: entry.signer_name || booking?.client_name || null,
    via: 'booking',
  };
}

export function isLegalDocSigned(doc, booking, inspections) {
  return Boolean(legalDocSignature(doc, booking, inspections)?.signature_url);
}

export function legalPackProgress(booking, inspections) {
  const docs = RENTAL_LEGAL_DOCS;
  const signed = docs.filter((d) => isLegalDocSigned(d, booking, inspections));
  const pickupDocs = docs.filter((d) => d.phase === 'pickup');
  const pickupSigned = pickupDocs.filter((d) => isLegalDocSigned(d, booking, inspections));
  const returnDocs = docs.filter((d) => d.phase === 'return');
  const returnSigned = returnDocs.filter((d) => isLegalDocSigned(d, booking, inspections));
  return {
    total: docs.length,
    signedCount: signed.length,
    pickupTotal: pickupDocs.length,
    pickupSignedCount: pickupSigned.length,
    returnTotal: returnDocs.length,
    returnSignedCount: returnSigned.length,
    pickupReady: pickupSigned.length === pickupDocs.length,
    returnReady: returnSigned.length === returnDocs.length,
    packComplete: signed.length === docs.length,
  };
}

