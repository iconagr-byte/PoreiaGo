/** Map nav / settings / rent ids → dictionary keys. */
export function adminLabelKey(kind, id) {
  if (!id) return null;
  if (kind === 'nav') return `nav_${id}`;
  if (kind === 'settings') return `settings_${id}`;
  if (kind === 'rent') return `rent_${id}`;
  if (kind === 'hint') return `hint_${id}`;
  if (kind === 'section') return `section_${id}`;
  return null;
}
